"""
Plan Optimizer Module
 (Automated Pruning)

Optimizes feature_processing_plan.json based on SHAP feature importance.
 SHAP  feature_processing_plan.json ()
"""

import json
import logging
import shutil
from pathlib import Path
from datetime import datetime
import pandas as pd
from typing import Dict, Union

logger = logging.getLogger(__name__)

def optimize_plan_by_shap(
    plan_path: Union[str, Path],
    importance_csv_path: Union[str, Path],
    drop_threshold: float = 0.001,
    backup_dir: Union[str, Path] = "output/visualization/feature_plans"
) -> int:
    """
    Read feature importance and update plan to DROP features below threshold.
    
    Args:
        plan_path: Path to current feature_processing_plan.json
        importance_csv_path: Path to feature_importance.csv generated by SHAP analysis
        drop_threshold: Features with importance < this will be marked 'drop'
        backup_dir: Directory to save previous plan version
        
    Returns:
        Number of features modified to 'drop'
    """
    plan_path = Path(plan_path)
    importance_csv_path = Path(importance_csv_path)
    backup_dir = Path(backup_dir)
    
    if not plan_path.exists():
        logger.error(f"Plan file not found: {plan_path}")
        return 0
        
    if not importance_csv_path.exists():
        logger.error(f"Importance file not found: {importance_csv_path}")
        return 0
        
    # 1. Backup Current Plan
    backup_dir.mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_path = backup_dir / f"plan_backup_{timestamp}.json"
    shutil.copy2(plan_path, backup_path)
    logger.info(f"Backed up current plan to {backup_path}")
    
    # 2. Load Data
    with open(plan_path, 'r', encoding='utf-8') as f:
        plan = json.load(f)
        
    importance_df = pd.read_csv(importance_csv_path)
    # Expected columns: 'feature', 'mean_abs_shap'
    if 'feature' not in importance_df.columns or 'mean_abs_shap' not in importance_df.columns:
        logger.error("Importance CSV missing required columns (feature, mean_abs_shap)")
        return 0
        
    # 3. Identify Low Importance Features
    low_imp_df = importance_df[importance_df['mean_abs_shap'] < drop_threshold]
    features_to_drop = set(low_imp_df['feature'].tolist())
    
    logger.info(f"Found {len(features_to_drop)} features below threshold {drop_threshold}")
    
    # 4. Update Plan
    modified_count = 0
    
    for feature_name, config in plan.items():
        # Check if feature is in drop list (and not already dropped)
        if feature_name in features_to_drop and config.get('action') != 'drop':
            # Preserve original method if we want to revert later, maybe?
            # For now, strict Drop
            plan[feature_name]['action'] = 'drop'
            plan[feature_name]['reason'] = f"AUTO-PRUNE: Low SHAP ({drop_threshold})"
            modified_count += 1
            
    # 5. Save Updated Plan
    if modified_count > 0:
        with open(plan_path, 'w', encoding='utf-8') as f:
            json.dump(plan, f, indent=2)
        logger.info(f"Updated {plan_path}: {modified_count} features marked for dropping.")
    else:
        logger.info("No features required updates based on current threshold.")
        
    return modified_count
